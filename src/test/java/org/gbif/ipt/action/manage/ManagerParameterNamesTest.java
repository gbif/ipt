import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * The manager actions only accept the nested parameters their forms submit, and only with a POST request, so a request
 * can't reach the live resource's users, organisation, sources or registry state.
 */
public class ManagerParameterNamesTest {

  private static final List<String> REFUSED_RESOURCE_PARAMETERS = List.of(
      "resource.creator.role", "resource.creator", "resource.modifier.role", "resource.managers",
      "resource.versionHistory[0].modifiedBy.role", "resource.organisation.agencyAccountPassword",
      "resource.organisation.doiPrefix", "resource.mappings[0].source.host", "resource.sources[0].sql",
      "resource.key", "resource.status", "resource.doi", "resource.identifierStatus", "resource.shortname",
      "resource.eml.title", "resource['creator'].role", "resource['key']", "resource('creator')",
      "RESOURCE.CREATOR.ROLE", "Resource.key", "resource", "Resource.coreType");

  private static final List<String> METADATA_RESOURCE_PARAMETERS = List.of(
      "resource.coreType", "resource.subtype", "resource.citationAutoGenerated",
      "resource.inferGeocoverageAutomatically", "resource.inferTaxonomicCoverageAutomatically",
      "resource.inferTemporalCoverageAutomatically");

  private static final List<String> SIMPLE_PARAMETERS = List.of("r", "id", "mid", "resources", "resourceType");

  private static final List<String> NESTED_PARAMETERS = List.of("eml.title", "eml.creators[0].firstName",
      "metadata.title");

  private static HttpServletRequest request(String method) {
    HttpServletRequest req = mock(HttpServletRequest.class);
    when(req.getMethod()).thenReturn(method);
    return req;
  }

  private static <T extends ManagerBaseAction> T post(T action) {
    action.withServletRequest(request("POST"));
    return action;
  }

  private ManagerBaseAction managerAction() {
    return new ManagerBaseAction(mock(SimpleTextProvider.class), mock(AppConfig.class),
        mock(RegistrationManager.class), mock(ResourceManager.class));
  }

  private MappingAction mappingAction() {
    return new MappingAction(mock(SimpleTextProvider.class), mock(AppConfig.class), mock(RegistrationManager.class),
        mock(ResourceManager.class), mock(ExtensionManager.class), mock(SourceManager.class),
        mock(VocabulariesManager.class));
  }

  private SourceAction sourceAction() {
    return new SourceAction(mock(SimpleTextProvider.class), mock(AppConfig.class), mock(RegistrationManager.class),
        mock(ResourceManager.class), mock(SourceManager.class), mock(JdbcSupport.class), mock(DataDir.class));
  }

  private MetadataAction metadataAction() {
    return new MetadataAction(mock(SimpleTextProvider.class), mock(AppConfig.class), mock(RegistrationManager.class),
        mock(ResourceManager.class), mock(VocabulariesManager.class), mock(InferredMetadataManager.class),
        mock(ConfigWarnings.class), mock(DataDir.class));
  }

  private CamtrapMetadataAction camtrapMetadataAction() {
    return new CamtrapMetadataAction(mock(SimpleTextProvider.class), mock(AppConfig.class),
        mock(RegistrationManager.class), mock(ResourceManager.class), mock(DataPackageMetadataValidator.class),
        mock(InferredMetadataManager.class), mock(DataPackageSchemaManager.class));
  }

  private List<ManagerBaseAction> actions() {
    return List.of(managerAction(), mappingAction(), sourceAction(), metadataAction(), camtrapMetadataAction());
  }

  @Test
  public void resourceParameters() {
    for (ManagerBaseAction action : actions()) {
      post(action);
      String name = action.getClass().getSimpleName();
      for (String param : REFUSED_RESOURCE_PARAMETERS) {
        assertFalse(action.acceptableParameterName(param), name + " should refuse " + param);
      }
      for (String param : SIMPLE_PARAMETERS) {
        assertTrue(action.acceptableParameterName(param), name + " should accept " + param);
      }
      for (String param : NESTED_PARAMETERS) {
        assertTrue(action.acceptableParameterName(param), name + " should accept " + param);
      }
    }
  }

  @Test
  public void resourceParametersOnlyForMetadataPages() {
    for (ManagerBaseAction action : List.of(managerAction(), mappingAction(), sourceAction())) {
      post(action);
      for (String param : METADATA_RESOURCE_PARAMETERS) {
        assertFalse(action.acceptableParameterName(param),
            action.getClass().getSimpleName() + " should refuse " + param);
      }
    }
    MetadataAction metadata = post(metadataAction());
    for (String param : METADATA_RESOURCE_PARAMETERS) {
      assertTrue(metadata.acceptableParameterName(param), "MetadataAction should accept " + param);
    }
    CamtrapMetadataAction camtrap = post(camtrapMetadataAction());
    for (String param : METADATA_RESOURCE_PARAMETERS) {
      boolean basicPageOnly = param.equals("resource.coreType") || param.equals("resource.subtype");
      assertEquals(!basicPageOnly, camtrap.acceptableParameterName(param), "CamtrapMetadataAction " + param);
    }
  }

  /**
   * A GET request (a link from another site, or the AJAX peek/report/locked requests) isn't CSRF-checked, so it
   * must not change the live resource or its objects.
   */
  @Test
  public void getRequestsOnlySetSimpleParameters() {
    for (String method : List.of("GET", "HEAD")) {
      for (ManagerBaseAction action : actions()) {
        action.withServletRequest(request(method));
        String name = action.getClass().getSimpleName() + " " + method;
        // the source action only accepts r and id, see sourceGetParameters()
        for (String param : action instanceof SourceAction ? List.of("r", "id") : SIMPLE_PARAMETERS) {
          assertTrue(action.acceptableParameterName(param), name + " should accept " + param);
        }
        for (String param : List.of("resource.coreType", "resource.citationAutoGenerated", "source.name",
            "sqlSource.host", "sqlSource.sql", "fileSource.fieldsTerminatedByEscaped", "mapping.idColumn",
            "fields[0].index", "eml.title", "tmap['x']", "tmap(x)")) {
          assertFalse(action.acceptableParameterName(param), name + " should refuse " + param);
        }
      }
    }
    // no request at all is treated like a GET
    assertFalse(sourceAction().acceptableParameterName("sqlSource.host"));
  }

  /**
   * rdbms and sqlSourcePassword are simple parameters, but their setters change the live SQL source.
   */
  @Test
  public void sourceGetParameters() {
    SourceAction action = sourceAction();
    action.withServletRequest(request("GET"));
    assertTrue(action.acceptableParameterName("r"));
    assertTrue(action.acceptableParameterName("id"));
    for (String param : List.of("rdbms", "sqlSourcePassword", "analyze", "sourceName", "sourceType", "url", "rows",
        "mid", "source.name")) {
      assertFalse(action.acceptableParameterName(param), "should refuse " + param);
    }
  }

  /**
   * With requireAnnotations, Struts only binds parameters whose setter or getter has @StrutsParameter.
   */
  @Test
  public void sourceSettersAnnotated() throws Exception {
    for (String setter : List.of("setAnalyze", "setRdbms", "setSqlSourcePassword", "setSourceName", "setSourceType",
        "setUrl")) {
      assertNotNull(SourceAction.class.getDeclaredMethod(setter, String.class).getAnnotation(StrutsParameter.class),
          setter);
    }
  }

  @Test
  public void mappingParameters() {
    MappingAction action = post(mappingAction());
    for (String param : List.of("mapping.idColumn", "mapping.idSuffix", "mapping.filter.column",
        "mapping.filter.comparator", "mapping.filter.filterTime", "mapping.filter.param", "fields[0].index",
        "fields[0].defaultValue", "doiUsedForDatasetId")) {
      assertTrue(action.acceptableParameterName(param), "should accept " + param);
    }
    for (String param : List.of("mapping.source.host", "mapping.source.resource.key", "mapping.extension.rowType",
        "mapping['extension'].title", "mapping.fields", "Mapping.source.sql")) {
      assertFalse(action.acceptableParameterName(param), "should refuse " + param);
    }
  }

  @Test
  public void sourceParameters() {
    SourceAction action = post(sourceAction());
    for (String param : List.of("source.name", "source.encoding", "source.dateFormat", "source.ignoreHeaderLines",
        "source.fieldsTerminatedByEscaped", "source.fieldsEnclosedByEscaped", "source.multiValueFieldsDelimitedBy",
        "source.sheetIdx", "fileSource.fieldsTerminatedByEscaped", "fileSource.fieldsEnclosedByEscaped",
        "sqlSource.host", "sqlSource.database", "sqlSource.username", "sqlSource.sql", "sqlSourcePassword", "rdbms",
        "sourceName", "sourceType", "url", "analyze")) {
      assertTrue(action.acceptableParameterName(param), "should accept " + param);
    }
    for (String param : List.of("source.resource.key", "source.resource", "sqlSource.resource.status",
        "fileSource.resource.shortname", "source['resource'].key", "Source.Resource.key", "source.file",
        "fileSource.file", "source", "sqlSource", "source.readable", "source.columns", "source.processing",
        "source.lastModified", "fileSource.rows", "fileSource.fileSize", "sqlSource.password", "sqlSource.sqlLimited",
        "sqlSource.rdbms.driver", "source['name']", "Source.name", "SqlSource.host")) {
      assertFalse(action.acceptableParameterName(param), "should refuse " + param);
    }
  }

  @Test
  public void resourceGetterBindsOneLevel() throws Exception {
    for (Class<?> cls : List.of(ManagerBaseAction.class, CamtrapMetadataAction.class)) {
      StrutsParameter annotation = cls.getDeclaredMethod("getResource").getAnnotation(StrutsParameter.class);
      assertNotNull(annotation, cls.getSimpleName());
      assertEquals(1, annotation.depth(), cls.getSimpleName());
    }
  }

  @Test
  public void registeredIptOnlyBoundByRegistrationAction() throws Exception {
    assertNull(BaseAction.class.getDeclaredMethod("getRegisteredIpt").getAnnotation(StrutsParameter.class));
    assertNotNull(
        RegistrationAction.class.getDeclaredMethod("getRegisteredIpt").getAnnotation(StrutsParameter.class));
  }
}
