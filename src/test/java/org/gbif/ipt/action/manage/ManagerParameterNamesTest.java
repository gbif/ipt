package org.gbif.ipt.action.manage;

import org.gbif.ipt.action.BaseAction;
import org.gbif.ipt.action.admin.RegistrationAction;
import org.gbif.ipt.config.AppConfig;
import org.gbif.ipt.config.DataDir;
import org.gbif.ipt.config.JdbcSupport;
import org.gbif.ipt.service.admin.ExtensionManager;
import org.gbif.ipt.service.admin.RegistrationManager;
import org.gbif.ipt.service.admin.VocabulariesManager;
import org.gbif.ipt.service.manage.ResourceManager;
import org.gbif.ipt.service.manage.SourceManager;
import org.gbif.ipt.struts2.SimpleTextProvider;

import java.util.List;

import org.apache.struts2.interceptor.parameter.StrutsParameter;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;

/**
 * The manager actions only accept the nested parameters their forms submit, so a request can't reach the live
 * resource's users, organisation, sources or registry state.
 */
public class ManagerParameterNamesTest {

  private static final List<String> REFUSED_RESOURCE_PARAMETERS = List.of(
      "resource.creator.role", "resource.creator", "resource.modifier.role", "resource.managers",
      "resource.versionHistory[0].modifiedBy.role", "resource.organisation.agencyAccountPassword",
      "resource.organisation.doiPrefix", "resource.mappings[0].source.host", "resource.sources[0].sql",
      "resource.key", "resource.status", "resource.doi", "resource.identifierStatus", "resource.shortname",
      "resource.eml.title", "resource['creator'].role", "resource['key']", "resource('creator')",
      "RESOURCE.CREATOR.ROLE", "Resource.key", "resource");

  private static final List<String> ACCEPTED_RESOURCE_PARAMETERS = List.of(
      "resource.coreType", "resource.subtype", "resource.citationAutoGenerated",
      "resource.inferGeocoverageAutomatically", "resource.inferTaxonomicCoverageAutomatically",
      "resource.inferTemporalCoverageAutomatically");

  private static final List<String> OTHER_PARAMETERS = List.of(
      "r", "eml.title", "eml.creators[0].firstName", "metadata.title", "resources", "resourceType", "id");

  private ManagerBaseAction managerAction() {
    return new ManagerBaseAction(mock(SimpleTextProvider.class), mock(AppConfig.class),
        mock(RegistrationManager.class), mock(ResourceManager.class));
  }

  private MappingAction mappingAction() {
    return new MappingAction(mock(SimpleTextProvider.class), mock(AppConfig.class), mock(RegistrationManager.class),
        mock(ResourceManager.class), mock(ExtensionManager.class), mock(SourceManager.class),
        mock(VocabulariesManager.class));
  }

  private SourceAction sourceAction() {
    return new SourceAction(mock(SimpleTextProvider.class), mock(AppConfig.class), mock(RegistrationManager.class),
        mock(ResourceManager.class), mock(SourceManager.class), mock(JdbcSupport.class), mock(DataDir.class));
  }

  @Test
  public void resourceParameters() {
    for (ManagerBaseAction action : List.of(managerAction(), mappingAction(), sourceAction())) {
      String name = action.getClass().getSimpleName();
      for (String param : REFUSED_RESOURCE_PARAMETERS) {
        assertFalse(action.acceptableParameterName(param), name + " should refuse " + param);
      }
      for (String param : ACCEPTED_RESOURCE_PARAMETERS) {
        assertTrue(action.acceptableParameterName(param), name + " should accept " + param);
      }
      for (String param : OTHER_PARAMETERS) {
        assertTrue(action.acceptableParameterName(param), name + " should accept " + param);
      }
    }
  }

  @Test
  public void mappingParameters() {
    MappingAction action = mappingAction();
    for (String param : List.of("mapping.idColumn", "mapping.idSuffix", "mapping.filter.column",
        "mapping.filter.comparator", "mapping.filter.filterTime", "mapping.filter.param", "fields[0].index",
        "fields[0].defaultValue", "doiUsedForDatasetId")) {
      assertTrue(action.acceptableParameterName(param), "should accept " + param);
    }
    for (String param : List.of("mapping.source.host", "mapping.source.resource.key", "mapping.extension.rowType",
        "mapping['extension'].title", "mapping.fields", "Mapping.source.sql")) {
      assertFalse(action.acceptableParameterName(param), "should refuse " + param);
    }
  }

  @Test
  public void sourceParameters() {
    SourceAction action = sourceAction();
    for (String param : List.of("source.name", "source.encoding", "source.dateFormat", "source.ignoreHeaderLines",
        "source.fieldsTerminatedByEscaped", "source.fieldsEnclosedByEscaped", "source.multiValueFieldsDelimitedBy",
        "source.sheetIdx", "fileSource.fieldsTerminatedByEscaped", "sqlSource.host", "sqlSource.database",
        "sqlSource.username", "sqlSource.sql", "sqlSource.sqlLimited")) {
      assertTrue(action.acceptableParameterName(param), "should accept " + param);
    }
    for (String param : List.of("source.resource.key", "source.resource", "sqlSource.resource.status",
        "fileSource.resource.shortname", "source['resource'].key", "Source.Resource.key", "source.file",
        "fileSource.file")) {
      assertFalse(action.acceptableParameterName(param), "should refuse " + param);
    }
  }

  @Test
  public void resourceGetterBindsOneLevel() throws Exception {
    for (Class<?> cls : List.of(ManagerBaseAction.class, CamtrapMetadataAction.class)) {
      StrutsParameter annotation = cls.getDeclaredMethod("getResource").getAnnotation(StrutsParameter.class);
      assertNotNull(annotation, cls.getSimpleName());
      assertEquals(1, annotation.depth(), cls.getSimpleName());
    }
  }

  @Test
  public void registeredIptOnlyBoundByRegistrationAction() throws Exception {
    assertNull(BaseAction.class.getDeclaredMethod("getRegisteredIpt").getAnnotation(StrutsParameter.class));
    assertNotNull(
        RegistrationAction.class.getDeclaredMethod("getRegisteredIpt").getAnnotation(StrutsParameter.class));
  }
}
