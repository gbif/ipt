package org.gbif.ipt.validation;

import org.gbif.ipt.model.User.Role;
import org.gbif.ipt.model.UserImportRow;
import org.gbif.ipt.service.admin.UserAccountManager;
import org.gbif.utils.file.csv.CSVReader;
import org.gbif.utils.file.csv.CSVReaderFactory;

import java.io.BufferedReader;
import java.io.File;
import java.io.IOException;
import java.io.Serial;
import java.io.Writer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

import org.apache.commons.lang3.StringUtils;
import org.apache.commons.lang3.Strings;
import org.apache.commons.lang3.math.NumberUtils;

import lombok.Getter;

import static org.gbif.ipt.validation.EmailValidationMessageTranslator.EMAIL_ERROR_TRANSLATIONS;

/**
 * Parses and validates a CSV file of user accounts to be created in bulk.
 * Expected columns (header row required, any order, case-insensitive): firstname, lastname, email and optionally role.
 * Passwords are never read from the file, they are generated by the IPT.
 */
public class UserImportValidator extends BaseValidator {

  // accounts are created in a single request, BCrypt hashing each password, so keep this small
  public static final int MAX_ROWS = 100;

  public static final String COLUMN_FIRSTNAME = "firstname";
  public static final String COLUMN_LASTNAME = "lastname";
  public static final String COLUMN_EMAIL = "email";
  public static final String COLUMN_ROLE = "role";

  private static final List<String> REQUIRED_COLUMNS = List.of(COLUMN_FIRSTNAME, COLUMN_LASTNAME, COLUMN_EMAIL);
  private static final List<String> DELIMITERS = List.of(",", ";", "\t");
  private static final String BOM = "\uFEFF";

  /**
   * Thrown when the file as a whole cannot be imported (e.g. missing columns). Carries an i18n key.
   */
  @Getter
  public static class UserImportException extends Exception {

    @Serial
    private static final long serialVersionUID = -2157368394162578113L;

    private final String key;
    private final String[] args;

    public UserImportException(String key, String... args) {
      super(key);
      this.key = key;
      this.args = args;
    }
  }

  /**
   * Parses the file and validates every row. Rows with problems are returned too, with their errors (i18n keys).
   *
   * @param file        uploaded CSV file (UTF-8)
   * @param userManager used to detect already existing accounts
   *
   * @return all non-empty rows of the file
   */
  public List<UserImportRow> parse(File file, UserAccountManager userManager) throws UserImportException {
    checkEncoding(file);
    String delimiter = detectDelimiter(file);

    List<UserImportRow> rows = new ArrayList<>();
    try (CSVReader reader = CSVReaderFactory.build(file, StandardCharsets.UTF_8.name(), delimiter, '"', 1)) {
      Map<String, Integer> columns = mapColumns(reader.header);

      while (reader.hasNext()) {
        String[] values = reader.next();
        if (values == null || Arrays.stream(values).allMatch(StringUtils::isBlank)) {
          continue;
        }
        if (rows.size() >= MAX_ROWS) {
          throw new UserImportException("admin.users.import.error.tooManyRows", String.valueOf(MAX_ROWS));
        }

        UserImportRow row = new UserImportRow();
        // currLineNumber counts the rows read after the header, so the header line is added
        row.setLine(reader.currLineNumber() + 1);
        row.setFirstname(value(values, columns.get(COLUMN_FIRSTNAME)));
        row.setLastname(value(values, columns.get(COLUMN_LASTNAME)));
        row.setEmail(StringUtils.lowerCase(value(values, columns.get(COLUMN_EMAIL)), Locale.ROOT));
        row.setRoleValue(value(values, columns.get(COLUMN_ROLE)));
        rows.add(row);
      }
    } catch (IOException e) {
      throw new UserImportException("admin.users.import.error.read", e.getMessage());
    }

    if (rows.isEmpty()) {
      throw new UserImportException("admin.users.import.error.empty");
    }
    validate(rows, userManager);
    return rows;
  }

  /**
   * Builds and validates rows from values edited in the browser. The arrays are parallel, one entry per row;
   * rows left completely empty are ignored.
   *
   * @return all non-empty rows
   */
  public List<UserImportRow> build(String[] lines, String[] firstnames, String[] lastnames, String[] emails,
                                   String[] roles, UserAccountManager userManager) throws UserImportException {
    int size = firstnames == null ? 0 : firstnames.length;
    List<UserImportRow> rows = new ArrayList<>();
    for (int i = 0; i < size; i++) {
      UserImportRow row = new UserImportRow();
      row.setFirstname(StringUtils.trimToNull(firstnames[i]));
      row.setLastname(StringUtils.trimToNull(element(lastnames, i)));
      row.setEmail(StringUtils.lowerCase(StringUtils.trimToNull(element(emails, i)), Locale.ROOT));
      row.setRoleValue(StringUtils.trimToNull(element(roles, i)));
      if (row.getFirstname() == null && row.getLastname() == null && row.getEmail() == null) {
        continue;
      }
      if (rows.size() >= MAX_ROWS) {
        throw new UserImportException("admin.users.import.error.tooManyRows", String.valueOf(MAX_ROWS));
      }
      // rows added in the browser have no line in the file
      row.setLine(NumberUtils.toInt(element(lines, i), 0));
      rows.add(row);
    }

    if (rows.isEmpty()) {
      throw new UserImportException("admin.users.import.error.empty");
    }
    validate(rows, userManager);
    return rows;
  }

  /**
   * (Re)validates all rows, replacing any previous errors.
   */
  public void validate(List<UserImportRow> rows, UserAccountManager userManager) {
    Set<String> seenEmails = new HashSet<>();
    for (UserImportRow row : rows) {
      row.getErrors().clear();
      validate(row, userManager, seenEmails);
    }
  }

  private void validate(UserImportRow row, UserAccountManager userManager, Set<String> seenEmails) {
    if (!exists(row.getFirstname(), 1)) {
      row.addError("validation.firstname.required");
    }
    if (!exists(row.getLastname(), 1)) {
      row.addError("validation.lastname.required");
    }

    String email = row.getEmail();
    if (!exists(email)) {
      row.addError("validation.email.required");
    } else {
      ValidationResult result = checkEmailValid(email);
      if (!result.isValid()) {
        row.addError(EMAIL_ERROR_TRANSLATIONS.getOrDefault(result.getMessage(), "validation.email.invalid"));
      } else if (!seenEmails.add(email)) {
        row.addError("admin.users.import.error.duplicate");
      } else if (userManager.get(email) != null) {
        row.addError("admin.users.import.error.exists");
      }
    }

    Role role = parseRole(row.getRoleValue());
    if (role == null) {
      row.addError("admin.users.import.error.role");
    }
    row.setRole(role);
  }

  /**
   * @return the role matching the value (case-insensitive), User if the value is empty, or null if not recognised
   */
  static Role parseRole(String value) {
    if (StringUtils.isBlank(value)) {
      return Role.User;
    }
    for (Role role : Role.values()) {
      if (role.name().equalsIgnoreCase(value.trim())) {
        return role;
      }
    }
    return null;
  }

  private Map<String, Integer> mapColumns(String[] header) throws UserImportException {
    Map<String, Integer> columns = new HashMap<>();
    if (header != null) {
      for (int i = 0; i < header.length; i++) {
        String name = StringUtils.lowerCase(StringUtils.trimToEmpty(Strings.CS.removeStart(header[i], BOM)), Locale.ROOT);
        columns.putIfAbsent(name, i);
      }
    }

    List<String> missing = REQUIRED_COLUMNS.stream().filter(c -> !columns.containsKey(c)).toList();
    if (!missing.isEmpty()) {
      throw new UserImportException("admin.users.import.error.columns", String.join(", ", missing));
    }
    return columns;
  }

  /**
   * Checks the whole file is valid UTF-8. The CSV reader would replace malformed input silently, so files saved in
   * another encoding (e.g. Windows-1252 by spreadsheet applications) would create accounts with garbled names.
   */
  private void checkEncoding(File file) throws UserImportException {
    // this reader reports malformed input instead of replacing it
    try (BufferedReader br = Files.newBufferedReader(file.toPath(), StandardCharsets.UTF_8)) {
      br.transferTo(Writer.nullWriter());
    } catch (CharacterCodingException e) {
      throw new UserImportException("admin.users.import.error.encoding");
    } catch (IOException e) {
      throw new UserImportException("admin.users.import.error.read", e.getMessage());
    }
  }

  /**
   * Picks the delimiter that occurs most often in the header line, so files saved by spreadsheet applications using
   * semicolons or tabs are supported too.
   */
  private String detectDelimiter(File file) throws UserImportException {
    String headerLine;
    try (BufferedReader br = Files.newBufferedReader(file.toPath(), StandardCharsets.UTF_8)) {
      headerLine = br.readLine();
    } catch (IOException e) {
      throw new UserImportException("admin.users.import.error.read", e.getMessage());
    }
    if (StringUtils.isBlank(headerLine)) {
      throw new UserImportException("admin.users.import.error.empty");
    }

    String best = DELIMITERS.get(0);
    int bestCount = 0;
    for (String d : DELIMITERS) {
      int count = StringUtils.countMatches(headerLine, d);
      if (count > bestCount) {
        best = d;
        bestCount = count;
      }
    }
    return best;
  }

  private static String element(String[] values, int index) {
    return values != null && index < values.length ? values[index] : null;
  }

  private static String value(String[] values, Integer index) {
    if (index == null || index >= values.length) {
      return null;
    }
    return StringUtils.trimToNull(values[index]);
  }
}
